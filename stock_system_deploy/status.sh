#!/usr/bin/env bash
echo "=================================================="
echo "           STOCK SYSTEM SERVICE STATUS            "
echo "=================================================="
sudo systemctl status stock-system.service --no-pager
echo ""
echo "=================================================="
echo "           PORT LISTENING CHECK (9012 & 443)      "
echo "=================================================="
sudo ss -tulpn | grep -E "9012|443|80" || sudo netstat -tulpn | grep -E "9012|443|80" || echo "Ports not currently active"
echo ""
echo "=================================================="
echo "           NGINX STATUS                           "
echo "=================================================="
sudo systemctl status nginx --no-pager | head -n 12
echo ""
echo "=================================================="
echo "           LOCAL CURL HEALTH CHECK (HTTP & HTTPS) "
echo "=================================================="
echo "--- Backend Port 9012 ---"
curl -I http://127.0.0.1:9012/ 2>/dev/null | head -n 5 || echo "Could not reach local port 9012"
echo ""
echo "--- HTTPS SSL Port 443 ---"
curl -k -I https://127.0.0.1/ 2>/dev/null | head -n 5 || echo "Could not reach local HTTPS port 443"
